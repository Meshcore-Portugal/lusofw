  /**
   * \brief  Draw the logo centered on the display.
   * \return Y coordinate of the logo's top row, so callers can place their own
   *         text relative to it.
   */
  static int drawLogoCentered(DisplayDriver* display) {
    const int logoX = (display->width() - LOGO_WIDTH) / 2;
    const int logoY = (display->height() - LOGO_HEIGHT) / 2;
    display->setColor(UIColor::corp_blue);
    display->drawXbm(logoX, logoY, LOGO, LOGO_WIDTH, LOGO_HEIGHT);
    return logoY;
  }

  /**
   * \brief  Draw the full splash: centered logo, website and one text line.
   * \param  bottomText  version info, "Turning OFF", etc.
   * \param  bottomColor color for the bottom line (the website is always
   *                     primary_txt).
   */
  static void drawBootScreen(DisplayDriver* display, const char* bottomText, ColorVal bottomColor) {
    const int logoY = drawLogoCentered(display);

    display->setColor(UIColor::primary_txt);
    display->setTextSize(1);
    display->drawTextCentered(display->width() / 2, logoY + WEBSITE_Y_OFFSET, WEBSITE);

    display->setColor(bottomColor);
    display->setTextSize(1);
    display->drawTextCentered(display->width() / 2, logoY + BOTTOM_LINE_Y_OFFSET, bottomText);
  }
